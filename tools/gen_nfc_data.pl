=head1 NAME

gen_nfc_data.pl - generate nfc_data.h from Unicode::UCD

=head1 SYNOPSIS

gen_nfc_data.pl > nfc_data.h

=head1 DESCRIPTION

Writes the tables a Unicode Normalization Form C check needs: canonical
combining classes, full canonical decompositions, primary composites, and
the ranges of assigned code points.  Hangul syllables are left out and must
be composed and decomposed arithmetically.  The data comes from the
Unicode::UCD module of the perl that runs the script, so the output follows
that perl's Unicode version, which it records.

The script stops with a message if Unicode::UCD returns a format or value
it does not expect.

=head1 CAVEATS

Requires perl 5.22 or newer.

=cut
