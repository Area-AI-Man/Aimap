#!/usr/bin/env perl
use 5.022;
use warnings;

use Unicode::UCD v0.610 qw( prop_invlist prop_invmap );

use constant UNICODE_MAX	=> 0x10ffff;
use constant HANGUL_FIRST	=> 0xac00;
use constant HANGUL_LAST	=> 0xd7a3;

my ( $ccc_r, $ccc_m, $ccc_f ) = prop_invmap("Canonical_Combining_Class");
my ( $dt_r, $dt_m, $dt_f ) = prop_invmap("Decomposition_Type");
my ( $dm_r, $dm_m, $dm_f, $dm_d ) = prop_invmap("Decomposition_Mapping");
my ( $gc_r, $gc_m, $gc_f ) = prop_invmap("General_Category");
my @fce = prop_invlist("Full_Composition_Exclusion");

die "Canonical_Combining_Class: format $ccc_f\n" unless $ccc_f eq "s";
die "Decomposition_Type: format $dt_f\n" unless $dt_f eq "s";
die "Decomposition_Mapping: format $dm_f\n" unless $dm_f eq "ad";
die "Decomposition_Mapping: default $dm_d\n" unless $dm_d eq "0";
die "General_Category: format $gc_f\n" unless $gc_f eq "s";
die "Full_Composition_Exclusion: empty\n" unless @fce;

# The inclusive range of inversion map entry $i, or () past U+10FFFF.
sub range_of {
	my ( $r, $i ) = @_;
	my $first = $r->[$i];
	my $last = ( defined $r->[ $i + 1 ] ? $r->[ $i + 1 ] : 0x110000 ) - 1;

	return () if $first > UNICODE_MAX;
	$last = UNICODE_MAX if $last > UNICODE_MAX;
	return ( $first, $last );
}

my @ccc;
for my $i ( 0 .. $#{$ccc_r} ) {
	my ( $first, $last ) = range_of( $ccc_r, $i ) or last;
	my $v = $ccc_m->[$i];

	die "Canonical_Combining_Class: value $v\n" unless $v =~ /^\d+$/;
	die "Canonical_Combining_Class: $v above 255\n" if $v > 255;
	push @ccc, [ $first, $last, $v ] if $v != 0;
}

my %canonical;
for my $i ( 0 .. $#{$dt_r} ) {
	my ( $first, $last ) = range_of( $dt_r, $i ) or last;

	next unless $dt_m->[$i] eq "Canonical";
	$canonical{$_} = 1 for $first .. $last;
}

my ( %dm, $hangul_seen );
for my $i ( 0 .. $#{$dm_r} ) {
	my ( $first, $last ) = range_of( $dm_r, $i ) or last;
	my $v = $dm_m->[$i];

	if ( ref $v ) {
		die sprintf( "Decomposition_Mapping: list for %04X..%04X\n",
		    $first, $last ) if $first != $last;
		$dm{$first} = [@$v] if $canonical{$first};
	} elsif ( $v eq "<hangul syllable>" ) {
		die sprintf( "Hangul syllables at %04X..%04X\n", $first,
		    $last ) if $first != HANGUL_FIRST || $last != HANGUL_LAST;
		$hangul_seen = 1;
	} elsif ( $v =~ /^\d+$/ ) {
		next if $v == $dm_d;
		for my $cp ( $first .. $last ) {
			$dm{$cp} = [ $v + $cp - $first ] if $canonical{$cp};
		}
	} else {
		die "Decomposition_Mapping: value $v\n";
	}
}
die "Decomposition_Mapping: no Hangul syllable range\n" unless $hangul_seen;

sub full_decomposition {
	my ($cp) = @_;

	return ($cp) unless $dm{$cp};
	return map { full_decomposition($_) } @{ $dm{$cp} };
}

my ( @decomp, $decomp_max );
$decomp_max = 0;
for my $cp ( sort { $a <=> $b } keys %dm ) {
	my @to = full_decomposition($cp);

	$decomp_max = @to if @to > $decomp_max;
	push @decomp, [ $cp, @to ];
}

my %excluded;
for ( my $i = 0; $i < @fce; $i += 2 ) {
	my $last = ( defined $fce[ $i + 1 ] ? $fce[ $i + 1 ] : 0x110000 ) - 1;

	$excluded{$_} = 1 for $fce[$i] .. $last;
}

my ( @comp, %pair );
for my $cp ( sort { $a <=> $b } keys %dm ) {
	my @to = @{ $dm{$cp} };

	next if @to != 2 || $excluded{$cp};
	die sprintf( "two composites for %04X %04X\n", @to )
	    if $pair{"@to"}++;
	push @comp, [ @to, $cp ];
}
@comp = sort { $a->[0] <=> $b->[0] || $a->[1] <=> $b->[1] } @comp;

my @assigned;
for my $i ( 0 .. $#{$gc_r} ) {
	my ( $first, $last ) = range_of( $gc_r, $i ) or last;

	next if $gc_m->[$i] eq "Cn";
	if ( @assigned && $assigned[-1][1] + 1 == $first ) {
		$assigned[-1][1] = $last;
	} else {
		push @assigned, [ $first, $last ];
	}
}

my $version = Unicode::UCD::UnicodeVersion();

