printf "\t{ 0x%04X, 0x%04X, %d },\n", @$_ for @ccc;
print "};\n\n";

print "static const struct nfc_decomp nfc_decomp[] = {\n";
for my $d (@decomp) {
	my ( $cp, @to ) = @$d;

	printf "\t{ 0x%04X, %d, { %s } },\n", $cp, scalar @to,
	    join( ", ", map { sprintf "0x%04X", $_ } @to );
}
print "};\n\n";

print "static const struct nfc_comp nfc_comp[] = {\n";
printf "\t{ 0x%04X, 0x%04X, 0x%04X },\n", @$_ for @comp;
