print "#define NFC_DECOMP_MAX\t\t$decomp_max\n";
print "#define NFC_HANGUL_FIRST\t0x", sprintf( "%04X", HANGUL_FIRST ), "\n";
print "#define NFC_HANGUL_LAST\t\t0x", sprintf( "%04X", HANGUL_LAST ), "\n";

print <<'EOL';

